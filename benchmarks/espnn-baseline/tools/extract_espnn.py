#!/usr/bin/env python3
"""
extract_espnn.py — dump a tflite model's tensors + ops + quant params as a C
header for the espnn-baseline zoo-model harness.

Usage:
  tools/generate_goldens/zoo/.venv/bin/python benchmarks/espnn-baseline/tools/extract_espnn.py \
      models/zoo/keyword_spotting/kws_micro_speech_int8.tflite \
      benchmarks/espnn-baseline/main/zoo_models/kws_model.h kws

Emits, per tensor: shape, dtype, values (int8/int32 C arrays).
Emits, per op: op_name, input/output tensor indexes (so the C runner can be
hand-wired per model), builtin options (stride/pad/dilation/activation) when
present. Quant params (zp/scale, per-channel) printed as comments + computed
mult/shift via the gemmlowp QuantizeMultiplier formula.

The C side (main.c) then wires esp_nn_* calls using these arrays, matching the
same-conditions rule: identical tflite + identical ramp fill input.
"""

import json
import struct
import sys

import numpy as np
from ai_edge_litert.interpreter import Interpreter

# gemmlowp-style quantize multiplier (single rounding, 30-bit)
def quantize_multiplier(real_multiplier):
    assert real_multiplier > 0
    q = real_multiplier * (1 << 31)
    if q >= (1 << 31):
        return (1 << 31) - 1, 0
    shift = 0
    while q >= (1 << 30):  # want < 2^30
        q /= 2.0
        shift += 1
    while q < (1 << 29):   # want >= 2^29
        q *= 2.0
        shift -= 1
    return int(round(q)), shift


def c_literal(name, arr, ctype):
    body = ", ".join(str(int(v)) for v in arr)
    return f"static const {ctype} {name}[{len(arr)}] = {{ {body} }};"


def dump_model(tflite_path, out_path, model_tag):
    interp = Interpreter(model_path=tflite_path)
    td = interp.get_tensor_details()
    ops = interp._get_ops_details()

    lines = []
    lines.append("/* Auto-generated by extract_espnn.py — DO NOT EDIT BY HAND. */")
    lines.append(f"/* model: {tflite_path}  tag: {model_tag} */")
    lines.append("")
    lines.append(f"#ifndef {model_tag.upper()}_MODEL_H")
    lines.append(f"#define {model_tag.upper()}_MODEL_H")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")

    # ---- per-tensor dump
    lines.append("/* tensors */")
    for i, d in enumerate(td):
        name = d["name"]
        shape = d["shape"]
        dtype = np.dtype(d["dtype"]).name
        q = d.get("quantization_parameters", {})
        # normalise zp/scale (may be numpy arrays)
        zps = np.asarray(q.get("zero_points", [0])).tolist()
        scs = np.asarray(q.get("scales", [1.0])).tolist()
        lines.append(f"/* t{i} '{name}' shape={shape.tolist()} dtype={dtype} "
                     f"zp={zps} scale={scs} */")
        try:
            t = interp.get_tensor(i)
        except Exception as e:  # noqa: BLE001
            lines.append(f"/*   (get_tensor failed: {e}) */")
            continue
        t = np.asarray(t)
        flat = t.reshape(-1)
        if flat.dtype == np.int8:
            lines.append(c_literal(f"{model_tag}_t{i}", flat.tolist(), "int8_t"))
        elif flat.dtype == np.int32:
            lines.append(c_literal(f"{model_tag}_t{i}", flat.tolist(), "int32_t"))
        elif flat.dtype == np.int64:
            lines.append(c_literal(f"{model_tag}_t{i}", flat.tolist(), "int64_t"))
        elif flat.dtype == np.float32:
            lines.append(c_literal(f"{model_tag}_t{i}", flat.tolist(), "float"))
        else:
            lines.append(f"/*   dtype {flat.dtype} values skipped */")
        lines.append("")

    # ---- per-op dump
    lines.append("/* ops (builtin) */")
    for i, op in enumerate(ops):
        opts = op.get("builtin_options") or {}
        lines.append(f"/* op{i} {op['op_name']} in={op['inputs']} out={op['outputs']} "
                     f"opts={json.dumps(opts)} */")
    lines.append("")

    # ---- quant summary for the C runner (per-op mult/shift computed)
    lines.append("/* input/output quant (for offsets) */")
    in_d = interp.get_input_details()[0]
    out_d = interp.get_output_details()[0]
    in_zp = int(np.asarray(in_d["quantization_parameters"]["zero_points"]).tolist()[0])
    out_zp = int(np.asarray(out_d["quantization_parameters"]["zero_points"]).tolist()[0])
    in_sc = float(np.asarray(in_d["quantization_parameters"]["scales"]).tolist()[0])
    out_sc = float(np.asarray(out_d["quantization_parameters"]["scales"]).tolist()[0])
    lines.append(f"/* input  zp={in_zp} scale={in_sc:.8e}  shape={in_d['shape'].tolist()} */")
    lines.append(f"/* output zp={out_zp} scale={out_sc:.8e}  shape={out_d['shape'].tolist()} */")
    lines.append("")

    # ---- reference output (for the harness MATCH check): run zero-point input
    interp.allocate_tensors()
    inp = np.full(in_d["shape"], in_zp, dtype=np.int8)
    interp.set_tensor(in_d["index"], inp)
    interp.invoke()
    ref_out = np.asarray(interp.get_tensor(out_d["index"])).reshape(-1).tolist()
    lines.append(c_literal(f"{model_tag}_ref_zp_output", ref_out, "int8_t"))
    lines.append("")

    lines.append(f"#endif /* {model_tag.upper()}_MODEL_H */")
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out_path}: {len(td)} tensors, {len(ops)} ops, "
          f"input zp={in_zp} scale={in_sc:.8e}, output zp={out_zp} scale={out_sc:.8e}")


if __name__ == "__main__":
    if len(sys.argv) != 4:
        print(__doc__)
        sys.exit(1)
    dump_model(sys.argv[1], sys.argv[2], sys.argv[3])
